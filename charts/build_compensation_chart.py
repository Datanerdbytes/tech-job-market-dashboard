#!/usr/bin/env python3
"""
tech_job_market :: compensation by job title and work arrangement.

Renders a Plotly figure comparing the disclosed average salary band
(average salary_min -> average salary_max) for the top 5 most in-demand job
titles, split by work arrangement (Remote / Onsite / Hybrid / Unknown).

Top panel  : grouped bars per role — a lighter bar for the average salary_min
             and a solid bar for the average salary_max, one pair per arrangement.
Bottom panel: stacked posting counts, showing how many postings in each cell
             actually disclose a range vs. how many are missing one. This is the
             caveat made visible: roughly 90% of postings carry no salary, so
             every average above rests on a small sample.

Data source
-----------
The SQL was generated by the Auto-Ontology semantic layer (text-to-SQL agent
against the compiled glossary) and then independently re-verified against the dbt
target. See charts/comp_by_role_arrangement.sql for the verbatim SQL and the
receipt of every run.

A missing bar means "no posting in that cell disclosed a range", not "this
arrangement pays nothing".

Usage
-----
    export TECH_JOB_MARKET_DSN='postgresql://postgres:***@localhost:5432/tech_job_market'
    python charts/build_compensation_chart.py
"""

from __future__ import annotations

import argparse
import os
import pathlib
import sys

import pandas as pd
import plotly.graph_objects as go
from plotly.subplots import make_subplots

# --------------------------------------------------------------------------------------
# Query: top 5 titles by demand (NULL titles excluded), rolled up to work arrangements.
# The rollup is a CASE expression over the certified `remote_policy_std` attribute.
# "Hybrid" absorbs every mixed arrangement (any hybrid, or remote+onsite together),
# because the silver layer stores combinations like 'Hybrid; Onsite; Remote'.
# --------------------------------------------------------------------------------------
ROLLUP_SQL = """
WITH top_job_titles AS (
    SELECT job_title
    FROM tech_job_market.jobmarket.jobs_silver
    WHERE job_title IS NOT NULL
    GROUP BY job_title
    ORDER BY COUNT(*) DESC, job_title ASC
    LIMIT 5
),
classified AS (
    SELECT
        j.job_title,
        CASE
            WHEN j.remote_policy_std IS NULL THEN 'Unknown'
            WHEN j.remote_policy_std ILIKE '%hybrid%'
              OR (j.remote_policy_std ILIKE '%remote%' AND j.remote_policy_std ILIKE '%onsite%') THEN 'Hybrid'
            WHEN j.remote_policy_std ILIKE '%remote%'
              AND j.remote_policy_std NOT ILIKE '%onsite%'
              AND j.remote_policy_std NOT ILIKE '%hybrid%' THEN 'Remote'
            WHEN j.remote_policy_std ILIKE '%onsite%'
              AND j.remote_policy_std NOT ILIKE '%remote%'
              AND j.remote_policy_std NOT ILIKE '%hybrid%' THEN 'Onsite'
            ELSE 'Unknown'
        END AS work_arrangement,
        j.salary_min,
        j.salary_max
    FROM tech_job_market.jobmarket.jobs_silver j
    INNER JOIN top_job_titles t ON j.job_title = t.job_title
)
SELECT
    c.job_title,
    c.work_arrangement,
    COUNT(*) AS postings,
    COUNT(c.salary_min) AS postings_with_salary,
    COUNT(*) - COUNT(c.salary_min) AS postings_without_salary,
    CAST(AVG(c.salary_min) AS NUMERIC) AS avg_salary_min,
    CAST(AVG(c.salary_max) AS NUMERIC) AS avg_salary_max
FROM classified c
GROUP BY c.job_title, c.work_arrangement
ORDER BY c.job_title, c.work_arrangement
"""

TITLE_SQL = """
SELECT job_title, COUNT(*) AS postings
FROM tech_job_market.jobmarket.jobs_silver
WHERE job_title IS NOT NULL
GROUP BY job_title
ORDER BY postings DESC, job_title
LIMIT 5
"""

# Ordered most-relevant first; "Unknown" is deliberately excluded from the
# compensation panels because an undisclosed arrangement cannot be priced.
ARRANGEMENTS = ["Remote", "Onsite", "Hybrid"]
COLORS = {
    "Remote": "#2E86AB",
    "Onsite": "#E4572E",
    "Hybrid": "#6A4C93",
    "Unknown": "#9E9E9E",
}
ARRANGEMENT_LEGEND = {
    "Remote": "Remote only",
    "Onsite": "On-site only",
    "Hybrid": "Hybrid / mixed",
}


def fetch_frames(conn) -> tuple[pd.DataFrame, pd.DataFrame]:
    rollup = pd.read_sql(ROLLUP_SQL, conn)
    titles = pd.read_sql(TITLE_SQL, conn)
    return rollup, titles


def _cell(rollup: pd.DataFrame, title: str, arrangement: str) -> dict:
    """Return the aggregate for one (title, arrangement) cell, or zeros."""
    hit = rollup[
        (rollup["job_title"] == title) & (rollup["work_arrangement"] == arrangement)
    ]
    if hit.empty:
        return {
            "postings": 0,
            "with_salary": 0,
            "without_salary": 0,
            "avg_min": None,
            "avg_max": None,
        }
    row = hit.iloc[0]
    return {
        "postings": int(row["postings"]),
        "with_salary": int(row["postings_with_salary"]),
        "without_salary": int(row["postings_without_salary"]),
        "avg_min": None if pd.isna(row["avg_salary_min"]) else float(row["avg_salary_min"]),
        "avg_max": None if pd.isna(row["avg_salary_max"]) else float(row["avg_salary_max"]),
    }


def build_figure(rollup: pd.DataFrame, titles: pd.DataFrame) -> go.Figure:
    # Most in-demand role at the top of the chart.
    title_order = list(titles["job_title"])[::-1]
    tick_labels = []
    for t in title_order:
        rows = rollup[rollup["job_title"] == t]
        total = int(rows["postings"].sum()) if len(rows) else 0
        with_sal = int(rows["postings_with_salary"].sum()) if len(rows) else 0
        pct = (100.0 * with_sal / total) if total else 0.0
        tick_labels.append(f"<b>{t}</b><br><sup>{total} postings · {with_sal} with range ({pct:.0f}%)</sup>")

    fig = make_subplots(
        rows=2,
        cols=1,
        shared_xaxes=True,
        row_heights=[0.72, 0.28],
        vertical_spacing=0.12,
    )

    # ---------------- Top panel: salary bands ----------------
    # Each bar's height is the average salary_max; an asymmetric error bar runs
    # DOWN from there to the average salary_min, so the bar itself reads as the
    # band [avg_salary_min .. avg_salary_max] instead of two unrelated bars.
    for arrangement in ARRANGEMENTS:
        cells = [_cell(rollup, t, arrangement) for t in title_order]
        mins = [c["avg_min"] for c in cells]
        maxs = [c["avg_max"] for c in cells]
        color = COLORS[arrangement]

        # A cell with no disclosed range has nothing to draw; keep the bar absent
        # rather than implying a zero salary.
        keep = [i for i, (lo, hi) in enumerate(zip(mins, maxs)) if lo is not None and hi is not None]
        x_keep = [title_order[i] for i in keep]
        y_keep = [maxs[i] for i in keep]
        minus = [maxs[i] - mins[i] for i in keep]
        plus = [0 for _ in keep]

        custom = [
            [
                f"{title_order[i]}<br>{ARRANGEMENT_LEGEND[arrangement]}",
                f"avg salary_min: ${mins[i]:,.0f}",
                f"avg salary_max: ${maxs[i]:,.0f}",
                f"{cells[i]['with_salary']} of {cells[i]['postings']} postings disclose a range",
            ]
            for i in keep
        ]

        fig.add_trace(
            go.Bar(
                x=x_keep,
                y=y_keep,
                name=ARRANGEMENT_LEGEND[arrangement],
                legendgroup=arrangement,
                offsetgroup=arrangement,
                showlegend=True,
                marker=dict(color=color, opacity=0.92, line=dict(color=color, width=1)),
                error_y=dict(
                    type="data",
                    symmetric=False,
                    array=plus,
                    arrayminus=minus,
                    color=color,
                    thickness=2.5,
                    width=6,
                ),
                customdata=custom,
                hovertemplate=(
                    "<b>%{customdata[0]}</b><br>%{customdata[1]}<br>%{customdata[2]}<br>"
                    "%{customdata[3]}<extra></extra>"
                ),
            ),
            row=1,
            col=1,
        )

    # ---------------- Bottom panel: disclosure coverage ----------------
    for arrangement in ARRANGEMENTS:
        cells = [_cell(rollup, t, arrangement) for t in title_order]
        with_sal = [c["with_salary"] for c in cells]
        without_sal = [c["without_salary"] for c in cells]
        color = COLORS[arrangement]

        fig.add_trace(
            go.Bar(
                x=title_order,
                y=with_sal,
                name=f"{ARRANGEMENT_LEGEND[arrangement]} — discloses range",
                legendgroup=f"{arrangement}-cov",
                offsetgroup=arrangement,
                showlegend=False,
                marker=dict(color=color, opacity=0.95, line=dict(color=color, width=1)),
                hovertemplate=(
                    f"<b>{ARRANGEMENT_LEGEND[arrangement]}</b><br>"
                    "%{x}<br>%{y} postings disclose a range<extra></extra>"
                ),
            ),
            row=2,
            col=1,
        )
        fig.add_trace(
            go.Bar(
                x=title_order,
                y=without_sal,
                name=f"{ARRANGEMENT_LEGEND[arrangement]} — no range",
                legendgroup=f"{arrangement}-cov",
                offsetgroup=arrangement,
                showlegend=False,
                marker=dict(
                    color=color,
                    opacity=0.22,
                    line=dict(color=color, width=1),
                ),
                hovertemplate=(
                    f"<b>{ARRANGEMENT_LEGEND[arrangement]}</b><br>"
                    "%{x}<br>%{y} postings have NO salary range<extra></extra>"
                ),
            ),
            row=2,
            col=1,
        )

    fig.update_layout(
        template="plotly_white",
        title=dict(
            text=(
                "<b>Compensation by job title and work arrangement</b>"
                "<br><sup>tech_job_market · top 5 roles by posting volume · "
                "Auto-Ontology semantic layer · USD · "
                "averages computed only over postings that disclose a range</sup>"
            ),
            x=0.01,
            xanchor="left",
        ),
        barmode="group",
        bargap=0.22,
        bargroupgap=0.06,
        xaxis=dict(type="category", categoryorder="array", categoryarray=title_order),
        yaxis=dict(
            title="Average disclosed salary band (USD)",
            tickprefix="$",
            tickformat=",.0f",
            gridcolor="#EAEAEA",
            zeroline=False,
        ),
        yaxis2=dict(
            title="Postings<br><sup>behind each band</sup>",
            gridcolor="#EAEAEA",
            zeroline=False,
        ),
        legend=dict(
            title="Work arrangement",
            orientation="h",
            yanchor="bottom",
            y=1.045,
            xanchor="right",
            x=1,
            bgcolor="rgba(255,255,255,0.85)",
        ),
        annotations=[
            dict(
                text="<b>Top</b>: bar height = average salary_max; the bar extends down to the "
                "average salary_min, so each bar spans the disclosed band. "
                "A missing bar means no posting in that cell disclosed a range.",
                showarrow=False,
                xref="paper",
                yref="paper",
                x=0,
                y=-0.22,
                xanchor="left",
                align="left",
                font=dict(size=11, color="#666"),
            ),
            dict(
                text="<b>Bottom</b>: solid = postings that disclose a range, faded = postings with no "
                "salary disclosed. Faded dominates everywhere, so each band above rests on a small sample.",
                showarrow=False,
                xref="paper",
                yref="paper",
                x=0,
                y=-0.30,
                xanchor="left",
                align="left",
                font=dict(size=11, color="#666"),
            ),
        ],
        margin=dict(l=90, r=40, t=140, b=170),
        height=820,
        width=1400,
        hoverlabel=dict(font_size=12),
    )

    fig.update_xaxes(
        tickmode="array",
        tickvals=title_order,
        ticktext=tick_labels,
        tickfont=dict(size=11),
        row=2,
        col=1,
    )
    # shared_xaxes renders the category labels from the bottom axis only; mirror
    # them onto row 1 so the posting-coverage subtitle is visible under every role.
    fig.update_xaxes(
        tickmode="array",
        tickvals=title_order,
        ticktext=tick_labels,
        tickfont=dict(size=11),
        row=1,
        col=1,
    )

    return fig


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--show", action="store_true", help="open the chart in a browser")
    parser.add_argument("--png", action="store_true", help="also export a static PNG")
    args = parser.parse_args()

    here = pathlib.Path(__file__).resolve().parent
    out_html = here / "compensation_by_role_and_arrangement.html"
    out_csv = here / "compensation_by_role_and_arrangement.csv"
    out_png = here / "compensation_by_role_and_arrangement.png"

    dsn = os.environ.get("TECH_JOB_MARKET_DSN")
    if not dsn:
        sys.exit(
            "Set TECH_JOB_MARKET_DSN to the tech_job_market Postgres DSN, e.g.\n"
            "  export TECH_JOB_MARKET_DSN='postgresql://postgres:***@localhost:5432/tech_job_market'"
        )

    import psycopg2

    conn = psycopg2.connect(dsn)
    try:
        rollup, titles = fetch_frames(conn)
    finally:
        conn.close()

    rollup.to_csv(out_csv, index=False)

    fig = build_figure(rollup, titles)
    fig.write_html(str(out_html), include_plotlyjs="cdn")
    print(f"wrote {out_html}")
    print(f"wrote {out_csv}")
    if args.png:
        fig.write_image(str(out_png), width=1400, height=820, scale=2)
        print(f"wrote {out_png}")
    if args.show:
        fig.show()

    print()
    print(rollup.to_string(index=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
